/**
 * Automatically looks up airline logo and aircraft image based on airline name
 * @param {string} airlineName 
 * @returns {{ name: string, logo: string, flight_img: string }}
 */
export const getAirlineAssets = (airlineName) => {
  if (!airlineName || typeof airlineName !== 'string') {
    return {
      name: 'Flight',
      logo: 'https://images.kiwi.com/airlines/64x64/default.png',
      flight_img: '/airlines/indigo.jpg'
    };
  }

  const clean = airlineName.trim().toLowerCase();

  // 1. Direct exact match
  if (AIRLINE_ASSETS[clean]) {
    return AIRLINE_ASSETS[clean];
  }

  // 2. Partial / keyword match
  for (const [key, asset] of Object.entries(AIRLINE_ASSETS)) {
    if (clean.includes(key) || key.includes(clean)) {
      return asset;
    }
  }

  // 3. Fallback with smart IATA code lookup or Kiwi generic logo
  const initials = clean.substring(0, 2).toUpperCase();
  return {
    name: airlineName,
    logo: `https://images.kiwi.com/airlines/64x64/${initials}.png`,
    flight_img: '/airlines/indigo.jpg'
  };
};

